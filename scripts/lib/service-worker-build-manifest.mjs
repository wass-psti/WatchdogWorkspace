import { createHash } from 'node:crypto';

export const SERVICE_WORKER_APP_VERSION = '1.43.2';
export const SERVICE_WORKER_STRATEGY_REVISION = 'm33-explicit-update-v1';

export function createServiceWorkerRuntimeManifest(paths, options = {}) {
  const appVersion = String(options.appVersion || SERVICE_WORKER_APP_VERSION);
  const strategyRevision = String(options.strategyRevision || SERVICE_WORKER_STRATEGY_REVISION);
  const unique = [...new Set(paths.map((path) => String(path)))].sort((a, b) => a.localeCompare(b));
  const buildId = createHash('sha256')
    .update(`${strategyRevision}\n${unique.join('\n')}`)
    .digest('hex')
    .slice(0, 16);
  const release = Object.freeze({
    schema: 'wm-runtime-release-v1',
    appVersion,
    strategyRevision,
    buildId,
    cacheNamespace: `work-management-v${appVersion}`,
  });
  const source = `/* Generated by Vite for Work Management ${appVersion}. */\nself.WM_RUNTIME_RELEASE = Object.freeze(${JSON.stringify(release, null, 2)});\nself.WM_RUNTIME_ASSETS = Object.freeze(${JSON.stringify(unique, null, 2)});\n`;
  return Object.freeze({ release, assets: Object.freeze(unique), source });
}

export function runtimeAssetsSource(paths, options = {}) {
  return createServiceWorkerRuntimeManifest(paths, options).source;
}
