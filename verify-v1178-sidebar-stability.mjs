import fs from 'node:fs';
import assert from 'node:assert/strict';
const shellCss = fs.readFileSync(new URL('./assets/css/shell-navigation.css', import.meta.url), 'utf8');
const tokens = fs.readFileSync(new URL('./assets/css/foundation/tokens.css', import.meta.url), 'utf8');
const appCss = fs.readFileSync(new URL('./assets/css/app.css', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('./assets/js/app.ts', import.meta.url), 'utf8');
const platform = fs.readFileSync(new URL('./assets/js/core/platform.ts', import.meta.url), 'utf8');
const sw = fs.readFileSync(new URL('./service-worker.js', import.meta.url), 'utf8');
assert.ok(platform.includes("PLATFORM_VERSION = '1.43.2'"), 'platform version mismatch');
assert.ok(sw.includes('work-management-v1.43.2'), 'service worker cache mismatch');
assert.ok(tokens.includes('--wm-shell-sidebar-width-default: 256px'), 'semantic desktop sidebar token missing');
assert.ok(tokens.includes('--wm-shell-sidebar-width-compact: 60px'), 'semantic compact sidebar token missing');
assert.match(shellCss, /\.sidebar\s*\{[\s\S]*position:\s*fixed;/, 'sidebar must remain viewport-fixed');
assert.ok(shellCss.includes('margin-left: var(--wm-shell-navigation-layout-width);'), 'workspace must consume semantic navigation layout width');
assert.ok(shellCss.includes('overflow-y: auto;'), 'short-viewport sidebar navigation must scroll independently');
assert.ok(shellCss.includes('env(safe-area-inset-bottom)'), 'mobile navigation must account for safe area');
assert.ok(shellCss.includes('data-shell-mobile-open="true"'), 'mobile drawer open-state contract is missing');
assert.doesNotMatch(appCss, /--wm-sidebar-width:250px/, 'retired v1.17.x fixed-width shell token returned');
assert.doesNotMatch(appCss, /padding-bottom:calc\(var\(--wm-mobile-nav-height\)/, 'retired mobile bottom rail returned');
assert.ok(app.includes('data-workspace-shell'), 'persistent shell contract missing');
console.log('v1.17.9 sidebar stability contract migrated to Shell M8: PASS');
